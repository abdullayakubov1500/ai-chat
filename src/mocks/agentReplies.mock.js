export function matchAgentReply(userText) {
  const normalized = userText.trim().toLowerCase();

  if (offTopicKeywords.some((kw) => normalized.includes(kw))) {
    return offTopicReply;
  }

  for (const scenario of scenarios) {
    if (scenario.keywords.some((kw) => normalized.includes(kw))) {
      return scenario.reply;
    }
  }

  const index = Math.abs(hashString(normalized)) % fallbackReplies.length;
  return fallbackReplies[index];
}

function hashString(str) {
  let hash = 0;
  for (let i = 0; i < str.length; i += 1) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  return hash;
}
